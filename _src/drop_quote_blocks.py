def main():
    src = Path(sys.argv[1])
    dst = Path(sys.argv[2])
    text = src.read_text(encoding="utf-8")
    parts = re.split(r"(?m)^## 第(\d{2})页\s*$", text)
    chunks = []
    for i in range(1, len(parts), 2):
        page = int(parts[i])
        body = parts[i + 1].strip()
        drop = set(DELETE.get(page, []))
        paras = body.split("\n\n")
        if paras and paras[-1].strip() == "---":
            paras.pop()
        kept = [p for p in paras if p.strip() not in drop]
        chunks.append(f"## 第{page:02d}页\n\n" + "\n\n".join(kept))
    header = (
        "# 《蛭文》教学读本 · 讲解文字稿\n\n"
        "共 95 页。保留原有讲解、分析与出处，仅删去大段引文与诗作原文。\n"
    )
    dst.write_text(header + "\n\n---\n\n" + "\n\n---\n\n".join(chunks) + "\n", encoding="utf-8")
    print(f"wrote {dst} ({dst.stat().st_size} bytes)")


if __name__ == "__main__":
    main()
